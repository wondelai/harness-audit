import { docsUrl, LEVELS, STATION_MAP, t } from './i18n.js';
import type { AuditReport, Lang } from './types.js';

export function generateFixPrompt(report: AuditReport, lang: Lang = report.lang): string {
  const actionable = report.checks.filter((c) => c.status === 'fail' || c.status === 'warn');
  const fails = actionable.filter((c) => c.status === 'fail');
  const warns = actionable.filter((c) => c.status === 'warn');
  const levelMeta = LEVELS[report.level];

  const stackSummary = [
    report.stack.languages.length > 0 ? `Languages: ${report.stack.languages.join(', ')}` : '',
    report.stack.frameworks.length > 0 ? `Frameworks: ${report.stack.frameworks.join(', ')}` : '',
    report.stack.packageManagers.length > 0 ? `Package managers: ${report.stack.packageManagers.join(', ')}` : '',
    `Layout: ${report.stack.monorepo ? 'Monorepo' : 'Single repository'} (${report.stack.sourceFileCount} source, ${report.stack.testFileCount} test files)`,
    report.stack.verifyScripts.length > 0 ? `Detected verify scripts: ${report.stack.verifyScripts.join(', ')}` : '',
  ]
    .filter(Boolean)
    .map((line) => `- ${line}`)
    .join('\n');

  const formatList = (items: typeof actionable): string =>
    items
      .map((c, i) => {
        const stationName = t(STATION_MAP[c.station].name, lang);
        return [
          `### ${i + 1}. \`${c.id}\` (${stationName} · ${c.status.toUpperCase()} · ${c.severity})`,
          `- **Issue:** ${t(c.title, lang)}`,
          `- **Observed evidence:** ${c.evidence.join(' ; ')}`,
          `- **Required fix:** ${t(c.fix, lang)}`,
          `- **Reference guide:** ${docsUrl(lang, c.docsPath)}`,
        ].join('\n');
      })
      .join('\n\n');

  if (lang === 'pl') {
    return `# HARNESS-FIX-PROMPT.md — Plan naprawy uprzęży agentów AI

> Wygenerowano przez \`@wondelai/harness-audit\` v${report.toolVersion} dla repozytorium \`${report.repoName}\`
> Aktualny wynik: **${report.overallScore}/100** · **Poziom ${report.level} (${levelMeta.shortName.pl})**

Wklej ten prompt do Claude Code, Codexa lub Cursora wewnątrz katalogu głównego repozytorium \`${report.repoName}\`.

---

## Kontekst repozytorium (wykryty deterministycznie)

${stackSummary}

${
  report.levelCaps.length > 0
    ? `### Aktywne ograniczenia poziomu (Level Caps)\n${report.levelCaps.map((c) => `- ${c.reason.pl} (\`${c.triggeredBy.join(', ')}\`)`).join('\n')}\n`
    : ''
}
## Zasady bezpieczeństwa i dyscyplina (OBOWIĄZKOWE)

1. **Nigdy nie nadpisuj ślepo istniejących instrukcji.** Jeśli \`AGENTS.md\`, \`CLAUDE.md\`, \`.claude/settings.json\` lub pliki reguł już istnieją, najpierw je przeczytaj i scal zmiany bez utraty istniejących ustaleń zespołu.
2. **Nie dotykaj konfiguracji globalnej użytkownika.** Nie modyfikuj \`~/.claude\`, \`~/.codex\`, \`~/.cursor\`, \`~/.gitconfig\` ani sekretów produkcyjnych. Pracuj wyłącznie w obrębie tego repozytorium.
3. **Każdą komendę zweryfikuj przez jej uruchomienie.** Nie wpisuj do \`AGENTS.md\` ani CI żadnej komendy, flagi ani skryptu, którego nie uruchomiłeś i nie potwierdziłeś w tym repozytorium.
4. **Nie osłabiaj istniejących testów ani reguł.** Jeśli test jest czerwony, napraw przyczynę — nie dodawaj \`.skip()\`, \`@ts-ignore\` ani tautologicznych asercji.
5. **Utrzymaj \`AGENTS.md\` poniżej 150 linii.** Przenieś szczegółowe zasady domenowe do reguł przypisanych do ścieżek (\`.claude/rules/*.md\` z \`paths:\` lub \`.cursor/rules/*.mdc\` z \`globs:\`), a \`CLAUDE.md\` utrzymuj jako cienki plik z gołą linią \`@AGENTS.md\`.
6. **Nie dodawaj martwych serwerów MCP.** Nigdy nie wpisuj wycofanych pakietów \`@modelcontextprotocol/server-postgres/-sqlite/-mysql/-slack/-git/-puppeteer\` ani sekretów w postaci jawnego tekstu; korzystaj ze zmiennych \`\${VAR}\`.

## Krytyczne błędy do naprawienia najpierw (${fails.length})

${fails.length > 0 ? formatList(fails) : '_Brak błędów krytycznych (FAIL)._'}

## Ostrzeżenia do domknięcia w drugiej kolejności (${warns.length})

${warns.length > 0 ? formatList(warns) : '_Brak ostrzeżeń (WARN)._'}

## Końcowy raport weryfikacji (wymagany format zakończenia)

Zakończ pracę wyłącznie po ponownym uruchomieniu \`npx @wondelai/harness-audit\` oraz wszystkich komend weryfikacji repozytorium. Wypisz poniższą tabelę dowodów (każde twierdzenie bez komendy i realnego wyniku uznajemy za niezweryfikowane):

| Twierdzenie / naprawiony check | Uruchomiona komenda | Kod wyjścia i skrót wyniku |
| --- | --- | --- |
| np. \`intent.single-source\` | \`npx @wondelai/harness-audit --format json\` | \`0 — status: pass\` |
`;
  }

  return `# HARNESS-FIX-PROMPT.md — Agent Harness Remediation Plan

> Generated by \`@wondelai/harness-audit\` v${report.toolVersion} for repository \`${report.repoName}\`
> Current score: **${report.overallScore}/100** · **Level ${report.level} (${levelMeta.shortName.en})**

Paste this prompt into Claude Code, Codex, or Cursor inside the root of \`${report.repoName}\`.

---

## Detected Repository Context

${stackSummary}

${
  report.levelCaps.length > 0
    ? `### Active Level Gating Caps\n${report.levelCaps.map((c) => `- ${c.reason.en} (\`${c.triggeredBy.join(', ')}\`)`).join('\n')}\n`
    : ''
}
## Hard Rules & Verification Discipline (MANDATORY)

1. **Never overwrite existing instructions blindly.** If \`AGENTS.md\`, \`CLAUDE.md\`, \`.claude/settings.json\`, or rule files already exist, read them completely first and merge edits surgically without dropping team invariants.
2. **Never touch global user configuration.** Do not edit \`~/.claude\`, \`~/.codex\`, \`~/.cursor\`, \`~/.gitconfig\`, or any live/production cloud resource. Stay strictly inside this repository.
3. **Verify every command by running it.** Do not write any build, lint, typecheck, or test command into \`AGENTS.md\` or CI unless you executed it in this checkout and observed its exit code.
4. **Never weaken tests or oracles.** Do not add \`.skip()\`, \`.only()\`, \`@ts-ignore\`, or tautological assertions (\`expect(true).toBe(true)\`) to turn checks green.
5. **Keep root \`AGENTS.md\` concise (<= 150 lines).** Put directory-specific rules into path-scoped files (\`.claude/rules/*.md\` with \`paths:\` frontmatter or \`.cursor/rules/*.mdc\` with \`globs:\`), and keep \`CLAUDE.md\` thin with a bare \`@AGENTS.md\` import line (not wrapped in backticks).
6. **Keep MCP configs clean.** Never add archived/non-existent npm packages (\`@modelcontextprotocol/server-postgres/-sqlite/-mysql/-slack/-git/-puppeteer\`), deprecated \`/sse\` URLs, or plaintext tokens; always use \`\${VAR}\` / \`\${env:VAR}\` interpolation and official vendor MCP registries.

## Failing Checks — Fix First (${fails.length})

${fails.length > 0 ? formatList(fails) : '_No failing checks — proceed to warnings below._'}

## Warnings — Harden Next (${warns.length})

${warns.length > 0 ? formatList(warns) : '_No warnings remaining._'}

## Required Verification Ledger (End Your Response With This Table)

Before finishing, re-run \`npx @wondelai/harness-audit\` and the repository's own verification commands. End with a claims → command → output ledger (any claim without an executed command and observed output is treated as unverified):

| Claim / Check Fixed | Command Executed | Exit Code & Observed Output |
| --- | --- | --- |
| e.g. \`intent.single-source\` | \`npx @wondelai/harness-audit --format json\` | \`0 — status: pass\` |
`;
}
